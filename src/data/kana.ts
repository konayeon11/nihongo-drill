let seq = 0

/** public/assets/hiragana|katakana/ 에 연상 이미지가 없는 글자 */
const NO_MNEMONIC_IMAGE = new Set<string>([])

function k(
  char: string,
  row: string,
  shape: string,
  mnemonic: string,
  opts: { confuse?: Confusion[] } = {},
): KanaItem {
  seq += 1
  const isKatakana = /[ァ-ヶ]/.test(char)
  const hex = char.codePointAt(0)!.toString(16)
  const hasImage = !NO_MNEMONIC_IMAGE.has(hex)
  const folder = isKatakana ? 'katakana' : 'hiragana'
  return {
    id: `kn-${String(seq).padStart(3, '0')}`,
    char,
    romaji: toRomaji(char),
    kind: isKatakana ? 'katakana' : 'hiragana',
    row,
    shape,
    mnemonic,
    confuse: opts.confuse,
    image: hasImage ? `assets/${folder}/${hex}.png` : undefined,
  }
}

function d(char: string, row: string, mnemonic: string): KanaItem {
  seq += 1
  return {
    id: `kn-${String(seq).padStart(3, '0')}`,
    char,
    romaji: toRomaji(char),
    kind: 'dakuten',
    row,
    shape: '탁음·반탁음',
    mnemonic,
  }
}

